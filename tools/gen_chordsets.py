"""The chord sets: data/chordsets/j6_chord_set_list.txt -> firmware/src/cr_chordsets.h and web/j6/chordsets.js.

    python3 tools/gen_chordsets.py           # writes both
    python3 tools/gen_chordsets.py --check   # exits 1 when either output is stale (CI, tests)

The list is the J-6's published Chord Set List (chord names and the notes of each voicing, as a manual prints them);
the outputs are tables of plain numbers and names. Each voicing is sorted low to high and de-duplicated; a few
obvious typos in the names are fixed (NAME_FIX)."""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "chordsets", "j6_chord_set_list.txt")
OUT_H = os.path.join(ROOT, "firmware", "src", "cr_chordsets.h")
OUT_JS = os.path.join(ROOT, "web", "j6", "chordsets.js")

KEYS = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
PC = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
NAME_FIX = {"F#FM7": "F#M7", "AbMb5/": "AbMb5/#9"}
STACK_SUFFIX = {"Oct Stack": "oct", "4th Stack": "4th", "5th Stack": "5"}
NOTES_MAX = 4
NAME_MAX = 13            # chars of a name (cr_chordsets.h CR_SET_NAME_MAX - 1)


def note_num(tok):
    m = re.fullmatch(r"([A-G])([#b]?)(-?\d)", tok)
    if not m:
        raise ValueError("bad note %r" % tok)
    pc = PC[m.group(1)] + (1 if m.group(2) == "#" else -1 if m.group(2) == "b" else 0)
    return 12 * (int(m.group(3)) + 1) + pc


def clean_name(name):
    name = NAME_FIX.get(name, name)
    name = re.sub(r"^([A-G][#b]?) +", r"\1", name)      # "D# dim7" -> "D#dim7"
    name = re.sub(r" +", " ", name).strip()
    return name


def parse(path):
    sets = []
    lines = [l.rstrip("\n") for l in open(path, encoding="utf-8") if l.strip() and not l.startswith("#")]
    if len(lines) % 2:
        raise ValueError("odd number of data lines")
    for i in range(0, len(lines), 2):
        a, b = lines[i].split("|"), lines[i + 1].split("|")
        n = int(a[0])
        if n != len(sets) + 1 or int(b[0]) != n or len(a) != 14 or len(b) != 13:
            raise ValueError("set %d: malformed rows" % n)
        genre = a[1].strip()
        chords = []
        for k in range(12):
            notes = sorted(set(note_num(t) for t in b[1 + k].split()))
            if not 2 <= len(notes) <= NOTES_MAX:
                raise ValueError("set %d key %s: %d notes" % (n, KEYS[k], len(notes)))
            name = clean_name(a[2 + k].strip())
            if not name:
                name = KEYS[k] + STACK_SUFFIX[genre]
            if len(name) > NAME_MAX:
                raise ValueError("set %d key %s: name %r too long" % (n, KEYS[k], name))
            chords.append({"name": name, "notes": notes})
        sets.append({"genre": genre, "chords": chords})
    if len(sets) != 100:
        raise ValueError("%d sets (100 expected)" % len(sets))
    return sets


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def make_h(sets):
    genres = []
    for s in sets:
        if s["genre"] not in genres:
            genres.append(s["genre"])
    o = []
    o.append("/* SPDX-License-Identifier: GPL-3.0-only")
    o.append(" * GENERATED by tools/gen_chordsets.py from data/chordsets/j6_chord_set_list.txt: do not edit.")
    o.append(" * The 100 chord sets (docs/CHORD-SETS.md): per set, a genre and for each of the 12 keys (C .. B) a chord name and")
    o.append(" * its voicing, MIDI notes low to high (0 = unused), as the set plays it from the key's octave C4 (cr_engine.c")
    o.append(" * crx_set_chord moves it to the key pressed). Included by cr_engine.c only. */")
    o.append("#ifndef CR_CHORDSETS_H")
    o.append("#define CR_CHORDSETS_H")
    o.append("")
    o.append("#define CR_NSETS %d" % len(sets))
    o.append("#define CR_SET_NOTES %d" % NOTES_MAX)
    o.append("#define CR_SET_NAME_MAX %d" % (NAME_MAX + 1))
    o.append("#define CR_SET_NGENRE %d" % len(genres))
    o.append("")
    o.append("static const char *const CR_SET_GENRES[CR_SET_NGENRE] = {")
    o.append("    " + ", ".join(c_str(g) for g in genres) + "};")
    o.append("static const uint8_t CR_SET_GENRE[CR_NSETS] = {")
    row = [str(genres.index(s["genre"])) for s in sets]
    for i in range(0, len(row), 25):
        o.append("    " + ", ".join(row[i:i + 25]) + ",")
    o.append("};")
    o.append("")
    o.append("static const uint8_t CR_SET_NOTE[CR_NSETS][12][CR_SET_NOTES] = {")
    for n, s in enumerate(sets):
        cells = []
        for ch in s["chords"]:
            v = ch["notes"] + [0] * (NOTES_MAX - len(ch["notes"]))
            cells.append("{" + ",".join(str(x) for x in v) + "}")
        o.append("    {" + ",".join(cells) + "},   /* %d %s */" % (n + 1, s["genre"]))
    o.append("};")
    o.append("")
    o.append("static const char CR_SET_NAME[CR_NSETS][12][CR_SET_NAME_MAX] = {")
    for n, s in enumerate(sets):
        o.append("    {" + ",".join(c_str(ch["name"]) for ch in s["chords"]) + "},")
    o.append("};")
    o.append("")
    o.append("#endif")
    return "\n".join(o) + "\n"


def make_js(sets):
    data = [{"n": i + 1, "genre": s["genre"], "chords": [[c["name"], c["notes"]] for c in s["chords"]]}
            for i, s in enumerate(sets)]
    body = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
    body = body.replace('},{"n"', '},\n{"n"')
    return ("// SPDX-License-Identifier: GPL-3.0-only\n"
            "// GENERATED by tools/gen_chordsets.py from data/chordsets/j6_chord_set_list.txt: do not edit.\n"
            "// The 100 chord sets: {n, genre, chords: [[name, [MIDI notes low to high]] x 12 keys C..B]}.\n"
            "export const CHORD_SETS = [\n" + body[1:-1] + "\n];\n")


def main():
    check = "--check" in sys.argv[1:]
    sets = parse(SRC)
    stale = 0
    for path, text in ((OUT_H, make_h(sets)), (OUT_JS, make_js(sets))):
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == text:
            continue
        if check:
            print("stale: %s (run tools/gen_chordsets.py)" % os.path.relpath(path, ROOT))
            stale = 1
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(path, ROOT))
    if check and not stale:
        print("chord sets: up to date (%d sets)" % len(sets))
    return stale


if __name__ == "__main__":
    sys.exit(main())
